"""Remote execution.

Everything here is read-only. Commands are generated by this package, never
taken from the web UI, and remote targets are passed as argv elements so no
controller-side shell interpolation of host data happens.
"""

from __future__ import annotations

import asyncio
from dataclasses import dataclass


class RemoteError(Exception):
    """Connection-level failure (auth, DNS, refused, timeout)."""


@dataclass
class ExecResult:
    stdout: str = ""
    stderr: str = ""
    exit_code: int = 0
    timed_out: bool = False
    error: str | None = None

    @property
    def ok(self) -> bool:
        return not self.timed_out and self.error is None and self.exit_code == 0

    def failure_reason(self) -> str | None:
        if self.timed_out:
            return self.error
        if self.error:
            return self.error
        if self.exit_code != 0:
            tail = (self.stderr or self.stdout).strip().splitlines()
            msg = tail[-1] if tail else ""
            return f"exit {self.exit_code}: {msg[:300]}".rstrip(": ")
        return None


async def _run(argv: list[str], stdin_data: str | None, timeout: int) -> ExecResult:
    proc = None
    try:
        proc = await asyncio.create_subprocess_exec(
            *argv,
            stdin=asyncio.subprocess.PIPE if stdin_data is not None else asyncio.subprocess.DEVNULL,
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE,
        )
        try:
            out, err = await asyncio.wait_for(
                proc.communicate(
                    stdin_data.encode("utf-8", "replace") if stdin_data is not None else None
                ),
                timeout=timeout,
            )
        except asyncio.TimeoutError:
            try:
                proc.kill()
            except ProcessLookupError:
                pass
            out, err = await proc.communicate()
            return ExecResult(
                stdout=out.decode("utf-8", "replace"),
                stderr=err.decode("utf-8", "replace"),
                exit_code=-1,
                timed_out=True,
                error=f"timed out after {timeout}s",
            )
        return ExecResult(
            stdout=out.decode("utf-8", "replace"),
            stderr=err.decode("utf-8", "replace"),
            exit_code=proc.returncode or 0,
        )
    except FileNotFoundError:
        return ExecResult(exit_code=-1, error=f"executable not found: {argv[0]}")
    except OSError as exc:
        return ExecResult(exit_code=-1, error=f"exec failed: {exc}")


class Runner:
    """Executes a script or a single command inside the target runtime."""

    kind = "unknown"

    async def run_script(self, script: str, timeout: int) -> ExecResult:
        raise NotImplementedError

    async def run_command(self, argv: list[str], timeout: int) -> ExecResult:
        raise NotImplementedError

    async def run_stdin(self, argv: list[str], script: str, timeout: int) -> ExecResult:
        raise NotImplementedError

    def describe(self) -> str:
        return self.kind


class LocalRunner(Runner):
    """Probe the machine running the backend; no SSH involved."""

    kind = "local"

    def __init__(self, shell: str = "sh"):
        self.shell = shell

    async def run_script(self, script: str, timeout: int) -> ExecResult:
        return await _run([self.shell, "-s"], script, timeout)

    async def run_command(self, argv: list[str], timeout: int) -> ExecResult:
        return await _run(argv, None, timeout)

    async def run_stdin(self, argv: list[str], script: str, timeout: int) -> ExecResult:
        return await _run(argv, script, timeout)


class _SshBase(Runner):
    def __init__(self, target: str, port: int | None = None, connect_timeout: int = 10):
        self.target = target
        self.port = port
        self.connect_timeout = connect_timeout

    def _base_argv(self) -> list[str]:
        argv = [
            "ssh",
            "-T",
            "-o",
            "BatchMode=yes",
            "-o",
            f"ConnectTimeout={self.connect_timeout}",
            "-o",
            "ServerAliveInterval=15",
            "-o",
            "ServerAliveCountMax=2",
            "-o",
            "LogLevel=ERROR",
        ]
        if self.port:
            argv += ["-p", str(self.port)]
        return argv

    async def run_command(self, argv_remote: list[str], timeout: int) -> ExecResult:
        return await _run(self._base_argv() + [self.target] + argv_remote, None, timeout)

    async def run_stdin(self, argv_remote: list[str], script: str, timeout: int) -> ExecResult:
        return await _run(self._base_argv() + [self.target] + argv_remote, script, timeout)

    def _target_label(self, prefix: str) -> str:
        return f"{prefix}:{self.target}" + (f":{self.port}" if self.port else "")


class SSHRunner(_SshBase):
    """POSIX remote: streams a script into sh -s over the user's OpenSSH client.

    Uses native ssh(1) so ~/.ssh/config entries (ProxyJump, IdentityFile,
    agent forwarding, Tailscale names) keep working untouched.
    """

    kind = "ssh"

    async def run_script(self, script: str, timeout: int) -> ExecResult:
        return await self.run_stdin(["sh", "-s"], script, timeout)

    def describe(self) -> str:
        return self._target_label("ssh")


class CommandRunner(_SshBase):
    """Raw remote command execution over SSH (used as a parent for WSL)."""

    kind = "ssh-raw"

    async def run_script(self, script: str, timeout: int) -> ExecResult:
        return await self.run_stdin(["sh", "-s"], script, timeout)

    def describe(self) -> str:
        return self._target_label("ssh")


class WindowsRunner(_SshBase):
    """Windows host reached over SSH, driving PowerShell remotely.

    Long scripts go over as UTF-16LE base64 with -EncodedCommand: piped stdin
    is executed line by line by PowerShell, which breaks multi-statement
    blocks, and inline quoting through cmd.exe is not survivable.
    """

    kind = "windows"

    def encode(self, script: str) -> str:
        import base64

        return base64.b64encode(script.encode("utf-16-le")).decode("ascii")

    async def run_script(self, script: str, timeout: int) -> ExecResult:
        return await self.run_command(
            [
                "powershell.exe",
                "-NoProfile",
                "-NonInteractive",
                "-ExecutionPolicy",
                "Bypass",
                "-EncodedCommand",
                self.encode(script),
            ],
            timeout,
        )

    def describe(self) -> str:
        return self._target_label("win-ssh")


class WslRunner(Runner):
    """A WSL distro inside a Windows host, reached through wsl.exe."""

    kind = "wsl"

    def __init__(self, parent: Runner, distro: str, user: str | None = None):
        self.parent = parent
        self.distro = distro
        self.user = user

    def _wrap(self, tail: list[str]) -> list[str]:
        argv = ["wsl.exe", "-d", self.distro]
        if self.user:
            argv += ["-u", self.user]
        return argv + ["--"] + tail

    async def run_script(self, script: str, timeout: int) -> ExecResult:
        return await self.parent.run_stdin(self._wrap(["sh", "-s"]), script, timeout)

    async def run_command(self, argv_remote: list[str], timeout: int) -> ExecResult:
        return await self.parent.run_command(self._wrap(argv_remote), timeout)

    async def run_stdin(self, argv_remote: list[str], script: str, timeout: int) -> ExecResult:
        return await self.parent.run_stdin(self._wrap(argv_remote), script, timeout)

    def describe(self) -> str:
        return f"wsl:{self.distro}@{self.parent.describe()}"
